#!/usr/bin/env bash
# Restrict the xentry web app's port to an allowlist of source addresses.
#
# xentry has no authentication: the middleware enforces Host/Origin/CSRF/JSON
# integrity, and the CSRF token is handed to any client that GETs /. Once the
# app is bound to a routable address, this packet filter is the only thing
# standing between the LAN and job submission, so it is a required part of a
# non-loopback deployment.
#
# Usage:
#   install-webfilter.sh 192.168.137.50 192.168.136.0/24 ...
#   PORT=8000 install-webfilter.sh ...
#
# The table is separate from the broker's `inet xentry`, which hooks forward and
# is deleted and re-added on every job phase; this one hooks input and is never
# touched by the broker. The chain policy is accept and only the app's port is
# filtered, so no other service (ssh included) can be locked out by it.
set -euo pipefail

PORT="${PORT:-8000}"
TABLE=xentry_admin
RULES_FILE=/etc/xentry/webfilter.nft
UNIT=/etc/systemd/system/xentry-webfilter.service

if [[ $EUID -ne 0 ]]; then
  echo "install-webfilter: run as root" >&2
  exit 2
fi
if [[ $# -eq 0 ]]; then
  echo "usage: $0 <allowed-source> [<allowed-source>...]" >&2
  echo "  e.g. $0 192.168.137.50 192.168.136.0/24" >&2
  exit 2
fi
if ! command -v nft >/dev/null 2>&1; then
  echo "install-webfilter: nft is not installed" >&2
  exit 2
fi

v4=() v6=()
for src in "$@"; do
  if [[ $src =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+(/[0-9]{1,2})?$ ]]; then
    v4+=("$src")
  elif [[ $src =~ ^[0-9a-fA-F:]+(/[0-9]{1,3})?$ && $src == *:* ]]; then
    v6+=("$src")
  else
    echo "install-webfilter: not an IPv4/IPv6 address or CIDR: $src" >&2
    exit 2
  fi
done

join() { local IFS=,; echo "$*"; }

{
  echo "#!/usr/sbin/nft -f"
  echo "# Generated by scripts/install-webfilter.sh. Allowlist for the xentry web app."
  echo "add table inet ${TABLE}"
  echo "delete table inet ${TABLE}"
  echo "table inet ${TABLE} {"
  echo "  chain input {"
  echo "    type filter hook input priority -10; policy accept;"
  echo "    iif lo tcp dport ${PORT} accept"
  [[ ${#v4[@]} -gt 0 ]] && echo "    tcp dport ${PORT} ip saddr { $(join "${v4[@]}") } accept"
  [[ ${#v6[@]} -gt 0 ]] && echo "    tcp dport ${PORT} ip6 saddr { $(join "${v6[@]}") } accept"
  echo "    tcp dport ${PORT} drop"
  echo "  }"
  echo "}"
} > "${RULES_FILE}.new"

# `add` then `delete` makes the file idempotent: it succeeds whether or not the
# table already exists, and the whole file applies as one transaction.
if ! nft -c -f "${RULES_FILE}.new"; then
  echo "install-webfilter: generated ruleset failed its syntax check; nothing applied" >&2
  rm -f "${RULES_FILE}.new"
  exit 4
fi

install -d -m 0755 /etc/xentry
install -m 0644 -o root -g root "${RULES_FILE}.new" "${RULES_FILE}"
rm -f "${RULES_FILE}.new"
nft -f "${RULES_FILE}"

cat > "$UNIT" <<UNITFILE
[Unit]
Description=xentry web app source allowlist (nftables)
Documentation=file:/opt/xentry/README.md
After=nftables.service
Before=xentry.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/nft -f ${RULES_FILE}

[Install]
WantedBy=multi-user.target
UNITFILE

systemctl daemon-reload
systemctl enable --now xentry-webfilter.service >/dev/null

echo "install-webfilter: applied ${RULES_FILE} and enabled xentry-webfilter.service"
nft list table inet "${TABLE}"
